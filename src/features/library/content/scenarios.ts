// ---------- помощники для сборки этапов ----------

type Part = { steps?: string[]; holdPoints?: string[]; photos?: string[] };

// Этап из частей: общие пункты + пункты конкретного сценария (по порядку)
function phase(name: string, ...parts: Part[]): Phase {
  return {
    name,
    steps: parts.flatMap(p => p.steps ?? []),
    holdPoints: parts.flatMap(p => p.holdPoints ?? []),
    photos: parts.flatMap(p => p.photos ?? []),
  };
}

type Draft = Omit<Scenario, 'sources' | 'status' | 'updated'> & Partial<Pick<Scenario, 'status' | 'updated'>>;

// Сценарий: по умолчанию «черновик ИИ»; список источников собирается из ссылок в тексте
function scenario(d: Draft): Scenario {
  const s = { status: 'черновик ИИ' as const, updated: CONTENT_DATE, ...d };
  return { ...s, sources: collectSources(s) };
}

